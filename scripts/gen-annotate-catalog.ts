/**
 * Bakes the annotation catalog and golden test cases for the Mac app's standalone mode.
 *
 * The Mac (standalone) has no server, so it runs a Swift port of `server/lib/annotate/catalogQuery.ts` over a copy
 * of the server's planner catalog (OpenNGC plus the curated extras such as the Sharpless objects and the curated
 * names). Baking it from the server's own code, rather than re-deriving it, keeps the two from drifting; the golden
 * cases are the server's answers for a set of frames, which the Swift tests must reproduce.
 *
 *   npx tsx scripts/gen-annotate-catalog.ts ../nebulis-apple/NebulisDesktop
 */
import fs from 'fs';
import path from 'path';
import { getCatalog, getPlannerCatalog } from '../server/lib/dsoCatalog';
import { annotateFrame } from '../server/lib/annotate/catalogQuery';
import { approximateWcs, type Wcs } from '../server/lib/annotate/wcs';

const outDir = process.argv[2];
if (!outDir) throw new Error('usage: gen-annotate-catalog.ts <NebulisDesktop dir>');

const DESIGNATION_NAME = /^(NGC|IC|M|C)\s?\d+$/i;
const base = new Set(getCatalog().map(e => e.id));
const rows = getPlannerCatalog().map(e => ({
  id: e.id,
  n: e.name,
  t: e.type,
  c: e.typeCode,
  ra: Number(e.ra.toFixed(6)),
  d: Number(e.dec.toFixed(6)),
  g: e.magnitude,
  s: e.majorAxisArcmin,
  m: e.messier != null ? 1 : 0,
  o: base.has(e.id) ? 1 : 0,
  a: e.commonNames.filter(n => DESIGNATION_NAME.test(n.trim())),
}));
fs.writeFileSync(path.join(outDir, 'Resources', 'annotate-catalog.json'), JSON.stringify(rows));
console.log(`catalog: ${rows.length} rows`);

// A real ASTAP solution of a SeeStar S50 stack of M42 (1080x1920), and of a Dwarf 3 stack (3840x2160).
const M42: Wcs = {
  crval1: 83.79613386179, crval2: -5.386288828626, crpix1: 540.5, crpix2: 960.5,
  cd: { cd11: -6.593422541755e-4, cd12: -1.469352722152e-5, cd21: -1.440460917071e-5, cd22: 6.594067638628e-4 },
  width: 1080, height: 1920,
};
const DWARF: Wcs = {
  crval1: 60.195588749896736, crval2: 36.283100336896013, crpix1: 1920.5, crpix2: 1080.5,
  cd: { cd11: 6.3061561520236090e-4, cd12: -4.4662319993362326e-4, cd21: -4.4693333343598791e-4, cd22: -6.2977458428487042e-4 },
  width: 3840, height: 2160,
};
const approx = (ra: number, dec: number, w: number, h: number, long: number) =>
  approximateWcs({ raDeg: ra, decDeg: dec, width: w, height: h, longSideDeg: long });
const at = (id: string): { ra: number; dec: number } => {
  const e = getPlannerCatalog().find(x => x.id === id);
  if (!e) throw new Error(`no catalog entry ${id}`);
  return { ra: e.ra * 15, dec: e.dec };
};

const cases: Array<{ name: string; wcs: Wcs; targetId: string | null }> = [
  { name: 'm42-solved', wcs: M42, targetId: 'M42' },
  { name: 'dwarf-california', wcs: DWARF, targetId: 'NGC1499' },
  { name: 'rosette-wide', wcs: approx(98.0, 4.95, 2048, 1152, 3), targetId: 'NGC2244' },
  { name: 'eagle-portrait', wcs: approx(274.72, -13.83, 1080, 1920, 1.28), targetId: 'M16' },
  { name: 'm31-field', wcs: approx(10.68, 41.27, 1152, 2048, 2.4), targetId: 'M31' },
  { name: 'm81-m82', wcs: approx(148.9, 69.4, 2048, 1152, 3), targetId: 'M81' },
  { name: 'sharpless-tulip', wcs: approx(at('SH2-101').ra, at('SH2-101').dec, 2048, 1152, 2.5), targetId: 'SH2-101' },
  { name: 'ra-wrap', wcs: approx(359.9, 16.1, 2048, 1152, 3), targetId: null },
  { name: 'near-pole', wcs: approx(at('NGC188').ra, at('NGC188').dec, 1080, 1920, 1.28), targetId: 'NGC188' },
  { name: 'double-number-ngc2520', wcs: approx(121.24, -28.15, 2048, 1152, 2), targetId: 'NGC2520' },
  { name: 'empty-sky', wcs: approx(300, -85, 1080, 1920, 1.28), targetId: null },
];
const golden = cases.map(c => ({
  name: c.name,
  targetId: c.targetId,
  wcs: c.wcs,
  expected: annotateFrame(c.wcs, { targetId: c.targetId }).map(a => ({
    id: a.id, label: a.label, designation: a.designation, typeCode: a.typeCode,
    x: Number(a.x.toFixed(3)), y: Number(a.y.toFixed(3)), r: Number(a.r.toFixed(3)),
    rTrue: Number(a.rTrue.toFixed(3)), oversized: a.oversized, isTarget: a.isTarget,
  })),
}));
// A Swift file rather than a JSON resource, so the test target needs no resource wiring.
fs.writeFileSync(
  path.join(outDir, 'Tests', 'AnnotationGoldenFixtures.swift'),
  `// Generated by nebulis-web/scripts/gen-annotate-catalog.ts from the server's annotateFrame. Do not edit.\n`
  + `enum AnnotationGolden {\n    static let json = #"""\n${JSON.stringify(golden)}\n"""#\n}\n`,
);
for (const g of golden) console.log(g.name.padEnd(24), g.expected.length, g.expected.slice(0, 4).map(a => a.id).join(','));
