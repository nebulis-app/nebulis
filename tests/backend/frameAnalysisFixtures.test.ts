import { describe, it, expect } from 'vitest';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { FRAME_METRICS_VERSION, measureFrame, type FrameMetrics } from '../../server/lib/frameAnalysis/measure';

/**
 * The server's analyzer against the fixtures it shares with the macOS app's port (see
 * scripts/gen-frame-analysis-fixtures.ts). The Mac project holds byte-identical copies and asserts the same
 * `expected.json` within a tolerance, so the two implementations cannot drift apart unnoticed.
 *
 * A failure here means a measurement changed. If that was the point: bump FRAME_METRICS_VERSION, regenerate with
 * `npx tsx scripts/gen-frame-analysis-fixtures.ts`, and copy the folder into the Mac project.
 */
const DIR = path.join(__dirname, '..', 'fixtures', 'frame-analysis');

interface Expected {
  version: number;
  files: Record<string, { sha256: string; metrics: FrameMetrics }>;
}

function loadExpected(): Expected {
  const parsed: unknown = JSON.parse(fs.readFileSync(path.join(DIR, 'expected.json'), 'utf8'));
  return parsed as Expected;
}

/**
 * Deep equality where numbers match to a relative 1e-9. The recorded values were written on another machine, and
 * the last digit of a float from atan2 or exp is not the same on every CPU and Node build.
 */
function expectClose(actual: unknown, expected: unknown, where: string): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    const tolerance = 1e-9 * Math.max(1, Math.abs(expected));
    expect(Math.abs(actual - expected), `${where}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
  } else if (Array.isArray(expected) && Array.isArray(actual)) {
    expect(actual.length, `${where} length`).toBe(expected.length);
    expected.forEach((e, i) => expectClose(actual[i], e, `${where}[${i}]`));
  } else if (expected !== null && typeof expected === 'object' && actual !== null && typeof actual === 'object') {
    expect(Object.keys(actual).sort(), `${where} keys`).toEqual(Object.keys(expected).sort());
    for (const [k, e] of Object.entries(expected)) expectClose((actual as Record<string, unknown>)[k], e, `${where}.${k}`);
  } else {
    expect(actual, where).toEqual(expected);
  }
}

describe('shared frame-analysis fixtures', () => {
  const expected = loadExpected();

  it('were generated by the current analyzer version', () => {
    expect(expected.version).toBe(FRAME_METRICS_VERSION);
  });

  for (const [name, entry] of Object.entries(expected.files)) {
    it(`${name} is the file the Mac copy is checked against`, () => {
      const buf = fs.readFileSync(path.join(DIR, name));
      expect(crypto.createHash('sha256').update(buf).digest('hex')).toBe(entry.sha256);
    });

    it(`${name} measures as recorded`, () => {
      const m = measureFrame(fs.readFileSync(path.join(DIR, name)));
      expectClose(m, entry.metrics, name);
    });
  }

  it('covers a clean, a trailed, a streaked, a sparse and a mosaic-pointed Bayer frame', () => {
    expect(Object.keys(expected.files).sort()).toEqual(
      ['bayer-pointed.fits', 'clean.fits', 'sparse.fits', 'streak.fits', 'trailed.fits'],
    );
  });
});
